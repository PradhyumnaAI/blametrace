"""Strict Pydantic data contracts shared across BlameTrace modules."""

from __future__ import annotations

from typing import Any

from pydantic import BaseModel, Field

SCHEMA_VERSION = "1.0.0"


class CulpritUnit(BaseModel):
    """A single internal unit (neuron, channel, head) verified via causal ablation."""

    layer_name: str = Field(..., description="Qualified PyTorch module path.")
    unit_index: int = Field(..., ge=0, description="Index along canonical Units axis.")
    triage_score: float = Field(
        ..., description="Stage-1 attribution score (e.g., Grad x Act)."
    )
    confidence_drop: float = Field(
        ..., description="Mean target scalar drop under clean-mean ablation."
    )
    flip_rate: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Fraction of failure samples fixed when this unit is ablated.",
    )
    null_zscore: float = Field(
        default=0.0,
        description="Effect size relative to random-unit null ablation in same layer.",
    )
    collateral_damage: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0,
        description="Fraction of clean samples degraded when this unit is ablated.",
    )
    anomaly_zscore: float = Field(
        default=0.0,
        description="Activation shift on failures relative to clean baseline mean/std.",
    )


class BranchBlameSplit(BaseModel):
    """Relative causal attribution across parallel branches in hybrid models."""

    stage_name: str
    branch_impacts: dict[str, float] = Field(
        default_factory=dict,
        description="Normalized causal impact share per branch (sums to ~1.0).",
    )
    gate_stats: dict[str, float] = Field(
        default_factory=dict,
        description="Summary statistics of fusion/gating weights on failures vs clean.",
    )


class FailurePattern(BaseModel):
    """A deduplicated failure mode backed by causal proof and optional explanation."""

    pattern_id: int = Field(..., ge=1)
    layer_name: str
    culprits: list[CulpritUnit]
    combined_flip_rate: float = Field(..., ge=0.0, le=1.0)
    combined_metric_gain: float = Field(
        default=0.0,
        description="Accuracy, error reduction, or Dice/IoU gain on joint ablation.",
    )
    evidence_summary: dict[str, Any] = Field(
        default_factory=dict,
        description="Structured offline evidence (top columns, patch coords, timesteps).",
    )
    plain_english_diagnosis: str | None = Field(
        default=None,
        description="Optional narrative generated by an LLM/VLM explainer.",
    )
    recommended_fix: str | None = Field(
        default=None,
        description="Actionable data, augmentation, or architecture recommendation.",
    )


class AuditReport(BaseModel):
    """Top-level output returned by a BlameTrace audit run."""

    schema_version: str = Field(default=SCHEMA_VERSION)
    model_name: str
    adapter_name: str
    task: str = Field(default="classification")
    num_clean_samples: int = Field(..., ge=0)
    num_failure_samples: int = Field(..., ge=0)
    patterns: list[FailurePattern] = Field(default_factory=list)
    branch_splits: list[BranchBlameSplit] = Field(default_factory=list)
